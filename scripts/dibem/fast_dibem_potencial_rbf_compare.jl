# ENV:
#   DIBEM_NDIVS=6,10,14,20
#   DIBEM_TIPO=1
#   DIBEM_FR=2.0
#   DIBEM_OUT=<paper-dir or plots/>
#   DIBEM_QUICK=1   # single ndiv smoke
#   DIBEM_METHODS=dense,hmatrix,fmm
